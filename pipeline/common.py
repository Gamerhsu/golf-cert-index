def canon_class(k):
    k = re.sub(r'\s+','', (k or '')).replace('（','(').replace('）',')')
    k = re.sub(r'\(\d+保\)','',k)
    k = re.sub(r'\(?\d+保證?金?\)?','',k)
    if k in CLASS_MAP: return CLASS_MAP[k]
    for pre,val in (("股東個人","股東個人"),("股東","股東眷屬"),("眷屬","眷屬"),
                    ("個人","個人"),("團體","團體")):
        if k.startswith(pre): return val
    return k or "個人"

def cells_of(row_html):
    out=[]
    for m in re.finditer(r'(?is)<t[dh]\b[^>]*>(.*?)</t[dh]>', row_html):
        c = re.sub(r'(?is)<(script|style).*?</\1>',' ', m.group(1))
        c = re.sub(r'(?i)<br\s*/?>',' ', c)
        c = re.sub(r'<[^>]+>',' ', c)
        c = html.unescape(c).replace('　',' ').replace('\xa0',' ')
        out.append(re.sub(r'\s+',' ', c).strip())
    return out

def parse_price(raw):
    """規則 3/4/7：區間、保證金、狀態 → (low, high, deposit, status)"""
    s = (raw or "").strip()
    if s in ("","-","－","—","–","‧"): return (None,None,None,None)
    for w in STATUS_WORDS:
        if w in s: return (None,None,None,w)
    dep=None
    m = re.search(r'[\(（]\s*([\d.]+)\s*保[^\)）]*[\)）]', s)
    if m: dep=float(m.group(1)); s = s[:m.start()]+s[m.end():]
    s2 = s.replace('，',',').replace('、',',').replace('﹑',',').replace('@','')
    nums = re.findall(r'\d+(?:\.\d+)?', s2)
    if not nums: return (None,None,dep,None)
    v=[float(x) for x in nums]
    if re.search(r'\d\s*[-~－〜–]\s*\d', s2) and len(v)>=2: return (min(v[:2]),max(v[:2]),dep,None)
    if len(v)>1: return (min(v),max(v),dep,None)
    return (v[0],v[0],dep,None)

def parse_fee(raw):
    """過戶費（萬元）。可能寫成 '20萬' / '20' / '8.625萬' / '@15萬'"""
    s=(raw or "").replace('@','').strip()
    if not s or s in ("-","－","—"): return None
    m=re.search(r'(\d+(?:\.\d+)?)', s)
    return float(m.group(1)) if m else None

def parse_dues(raw):
    """規則 6：年費/季費 → 年化（元）
       注意：部分來源把數字寫成「年 : 6 ,000」（數字內含空格），
       必須先清掉數字之間的空白與逗號，否則只會抓到 6。"""
    s=(raw or "").replace('@','')
    if not s or s.strip() in ("-","－","—"): return None
    # 先移除民國日期片語，否則「115年10月起過戶費調整」會被讀成「年 10」
    s=re.sub(r'\d{2,3}\s*年\s*\d{1,2}\s*月', ' ', s)
    s=re.sub(r'\d{2,3}\s*年度?起', ' ', s)
    # 清掉數字群組之間的空白與千分位符號：「6 ,000」→「6000」
    s=re.sub(r'(?<=\d)[\s,，]+(?=\d)', '', s)
    s=s.replace(',','').replace('，','')
    val=None
    for kw, mult in (('季',4), ('月',12), ('年',1)):
        m=re.search(kw+r'\s*[:：]?\s*(\d+(?:\.\d+)?)', s)
        if m: val=float(m.group(1))*mult; break
    if val is None:
        m=re.search(r'(\d{3,})', s)
        val=float(m.group(1)) if m else None
    # 合理性下限：全台最低的年費約 5,000 元（季費 1,244 × 4），
    # 低於 500 一律視為誤讀說明文字，寧可留空也不要餵錯數字進試算
    if val is not None and val < 500: return None
    return val

